CREATE TABLE TRANSACTION_TYPE
(
    TR_TYPE CHAR(2) NOT NULL,
    TR_DESCRIPTION VARCHAR(50) NOT NULL,
    PRIMARY KEY(TR_TYPE)
);

CREATE UNIQUE INDEX XTRAN_TYPE
    ON TRANSACTION_TYPE (TR_TYPE ASC);

